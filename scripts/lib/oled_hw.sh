# Candidate buses: prefer i2c-7 (RK3399 I2C7), then scan others except known SoC internals carefully.
# We do NOT blindly hammer every address on every bus forever; short probes only.

cot_r_list_i2c_buses() {
  local d
  for d in /dev/i2c-*; do
    [[ -e "$d" ]] || continue
    printf '%s\n' "$d"
  done
}

# Probe a single bus for common OLED addresses. Prints "bus=N addr=0xXX" if found.
# Prefer i2cdetect (address ACK). Avoid i2cget … 0x00 alone: some SSD1306/SH1106
# clones ACK on the bus but NAK register reads, which falsely reports "not found".
cot_r_probe_bus_ssd1306() {
  local busdev="$1"
  local busnum addr table
  busnum="${busdev##*/i2c-}"
  command -v i2cdetect >/dev/null 2>&1 || return 1
  table="$(i2cdetect -y "$busnum" 2>/dev/null)" || return 1
  for addr in 3c 3d; do
    # Match a matrix cell (e.g. "3c"), not the row label "30:".
    if printf '%s\n' "$table" | grep -Eq "(^|[[:space:]])${addr}([[:space:]]|$)"; then
      printf 'bus=%s addr=0x%s\n' "$busnum" "$addr"
      return 0
    fi
  done
  # Fallback for odd i2cdetect builds: try a plain presence get.
  for addr in 0x3c 0x3d; do
    if i2cget -y "$busnum" "$addr" 0x00 >/dev/null 2>&1 \
      || i2cget -y "$busnum" "$addr" >/dev/null 2>&1; then
      printf 'bus=%s addr=%s\n' "$busnum" "$addr"
      return 0
    fi
  done
  return 1
}

cot_r_discover_oled() {
  local busdev result preferred="/dev/i2c-7"
  if [[ -e "$preferred" ]]; then
    if result="$(cot_r_probe_bus_ssd1306 "$preferred")"; then
      printf '%s\n' "$result"
      return 0
    fi
  fi
  # Fall back: check other buses for 0x3c/0x3d only (no full-bus scan).
  for busdev in $(cot_r_list_i2c_buses); do
    [[ "$busdev" == "$preferred" ]] && continue
    if result="$(cot_r_probe_bus_ssd1306 "$busdev")"; then
      cot_r_warn "OLED responded on ${busdev} (expected i2c-7); using discovery result"
      printf '%s\n' "$result"
      return 0
    fi
  done
  return 1
}

cot_r_write_oled_config() {
  local bus="$1"
  local addr="$2"
  local driver="${3:-ssd1306}"
  local conf="${COT_R_ETC_DIR}/display.env"
  mkdir -p "${COT_R_ETC_DIR}"
  if [[ -f "$conf" ]]; then
    backup_file "$conf" >/dev/null
  fi
  cat >"$conf" <<EOF
# Generated by cot-r prepare. Secrets do not belong here.
# Copyright (C) 2026 Markus. SPDX-License-Identifier: AGPL-3.0-only
COT_R_I2C_BUS=${bus}
COT_R_I2C_ADDRESS=${addr}
COT_R_DISPLAY_DRIVER=${driver}
COT_R_DISPLAY_WIDTH=128
COT_R_DISPLAY_HEIGHT=64
COT_R_DISPLAY_SOCKET=${COT_R_DISPLAY_SOCK}
COT_R_DISPLAY_MAX_FPS=10
COT_R_DISPLAY_ORIENTATION=0
EOF
  chmod 0640 "$conf"
  # Readable by display and management (group cot-r via /etc/cot-r dir group).
  chown "root:${COT_R_DEPLOY_USER}" "$conf" 2>/dev/null || \
    chown "root:${COT_R_DISPLAY_USER}" "$conf" 2>/dev/null || true
  cot_r_manifest_add_file "$conf" "config"
  cot_r_ok "Wrote ${conf} (bus=${bus} addr=${addr} driver=${driver})"
}

cot_r_oled_selftest() {
  local conf="${COT_R_ETC_DIR}/display.env"
  local bus addr
  if [[ ! -f "$conf" ]]; then
    cot_r_warn "No ${conf}; attempting discovery"
    local disc
    if ! disc="$(cot_r_discover_oled)"; then
      cot_r_warn "OLED not found; skipping self-test (non-fatal)"
      return 0
    fi
    # disc like bus=7 addr=0x3c
    bus="${disc#bus=}"; bus="${bus%% *}"
    addr="${disc##*addr=}"
    cot_r_write_oled_config "$bus" "$addr"
  else
    # shellcheck disable=SC1090
    source "$conf"
    bus="${COT_R_I2C_BUS}"
    addr="${COT_R_I2C_ADDRESS}"
  fi

  local out
  if ! out="$(python3 - <<PY
import sys
try:
    from luma.core.interface.serial import i2c
    from luma.core.render import canvas
    from luma.oled import device as oled_dev
except ImportError as e:
    print("missing python deps:", e, file=sys.stderr)
    sys.exit(2)

bus = int("${bus}")
addr = int("${addr}", 0)
forced = "${COT_R_DISPLAY_DRIVER:-}".strip().lower()
candidates = []
if forced in ("ssd1306", "sh1106"):
    candidates = [forced]
else:
    candidates = ["ssd1306", "sh1106"]

last = None
for name in candidates:
    cls = getattr(oled_dev, name, None)
    if cls is None:
        continue
    try:
        serial = i2c(port=bus, address=addr)
        device = cls(serial, width=128, height=64)
        with canvas(device) as draw:
            draw.rectangle(device.bounding_box, outline="white", fill="black")
            draw.text((4, 8), "Cardano on", fill="white")
            draw.text((4, 24), "the Rocks", fill="white")
            draw.text((4, 44), f"OLED OK ({name})", fill="white")
        print(f"oled-ok bus={bus} addr={hex(addr)} driver={name}")
        sys.exit(0)
    except Exception as e:
        last = e
print(f"oled-error: {last}", file=sys.stderr)
sys.exit(1)
PY
)"; then
    local rc=$?
    if [[ "$rc" -eq 2 ]]; then
      cot_r_warn "Display Python packages missing; install via prepare"
      return 0
    fi
    cot_r_warn "OLED self-test failed (non-fatal for networking): exit ${rc}"
    printf '%s\n' "$out" >&2
    return 0
  fi
  printf '%s\n' "$out"
  # Persist whichever driver worked (ssd1306|sh1106).
  if [[ "$out" =~ driver=([a-z0-9]+) ]]; then
    cot_r_write_oled_config "$bus" "$addr" "${BASH_REMATCH[1]}"
  fi
  cot_r_ok "OLED self-test rendered successfully"
}

cot_r_cmd_oled_test() {
  cot_r_init_logging
  if [[ "${EUID}" -ne 0 ]]; then
    cot_r_warn "Running without root; I2C access may fail depending on udev/group"
  fi
  if ! command -v i2cdetect >/dev/null 2>&1; then
    die "i2c-tools not installed; run: sudo ./scripts/cot-r prepare"
  fi
  echo "I2C adapters:"
  i2cdetect -l || true
  local disc
  if disc="$(cot_r_discover_oled)"; then
    echo "Discovery: ${disc}"
    local bus addr
    bus="${disc#bus=}"; bus="${bus%% *}"
    addr="${disc##*addr=}"
    if [[ "${EUID}" -eq 0 ]]; then
      cot_r_write_oled_config "$bus" "$addr"
    fi
    # Show a short detect table for that bus only
    echo "Probe table for bus ${bus} (reference):"
    i2cdetect -y "$bus" || true
  else
    cot_r_warn "No SSD1306 at 0x3c/0x3d on available buses"
    cot_r_warn "If overlay was just added, reboot and retry"
    return 0
  fi
  cot_r_oled_selftest
}
